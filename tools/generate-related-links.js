#!/usr/bin/env node
/* ============================================================================
   generate-related-links.js
   ----------------------------------------------------------------------------
   Generation-time internal cross-linking for the content directories
   (guides/, blog/, trips/): computes a simple keyword/tag-overlap similarity
   between every content page and injects a "Related guides" / "Related
   articles" / "Related itineraries" section near the end of each page.

   This is deliberately a simple, "good enough" heuristic — not an ML/NLP
   similarity engine — matching the actual size of the corpus (~210 static
   HTML pages) and the fact that these pages are already largely
   auto-generated from a handful of templates. It scores candidate pages on:

     1. Tag overlap  — <span class="tag">...</span> values, when present
        (Jaccard over the tag set). Highest-precision signal, but only ~15
        guides currently carry tags.
     2. Keyword overlap — Jaccard over a filtered bag of words drawn from
        each page's <title>, meta description, <h1>, tags and filename
        slug, after stripping English stopwords and this corpus's own
        template boilerplate ("best", "time", "visit", "2026", "weather",
        "crowd", "budget", ... — words that appear on nearly every page
        and would otherwise swamp the real topic signal).
     3. Literal destination mention — if a guide/trip page's extracted
        destination name (e.g. "Kyoto") appears as a whole word/phrase in
        another page's body text, that's treated as a strong, high-
        confidence relatedness signal (this is what makes "a blog post
        about Kyoto tips auto-links to guides/kyoto-japan.html" work, per
        the brief).

   Output is idempotent: re-running with no content changes produces byte-
   identical files. The injected block is wrapped in HTML comment markers
   so a rerun replaces it in place instead of duplicating it. On the first
   run against a guides/ page that already ships a hand-authored
   "<h2>Keep exploring</h2><div class="grid">...</div>" block (a static,
   never-updated predecessor of this same idea), that legacy block is
   replaced by the marked, regenerable one rather than left duplicated.

   Usage:
     node tools/generate-related-links.js          # regenerate in place
     node tools/generate-related-links.js --check  # dry run; exits 1 if
                                                     # any file would change
     npm run related-links
     npm run related-links:check
   ========================================================================= */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SITE = 'https://www.roamwise.co.in';

// Directories this tool manages, and what to call their pages in the UI
// copy ("Related guides" / "Related articles" / "Related itineraries").
const SECTIONS = [
  { dir: 'guides', urlPrefix: '/guides/', label: 'Related guides', bucket: 'guides' },
  { dir: 'blog', urlPrefix: '/blog/', label: 'Related articles', bucket: 'blog' },
  { dir: 'trips', urlPrefix: '/trips/', label: 'Related itineraries', bucket: 'trips' },
];

// Pages that are hub/listing pages, not individual content pages — never a
// source for injection, but their siblings still list them as candidates
// via SECTIONS above (they simply never appear on the candidate list below
// because we filter them out entirely).
const SKIP_FILES = new Set(['index.html', 'read.md']);

const MARKER_START =
  '<!-- rw:related-links:start (auto-generated by tools/generate-related-links.js -- run `npm run related-links` to refresh, do not hand-edit) -->';
const MARKER_END = '<!-- rw:related-links:end -->';
const MARKER_RE = /<!-- rw:related-links:start[\s\S]*?<!-- rw:related-links:end -->/;
const LEGACY_KEEP_EXPLORING_RE = /<h2>Keep exploring<\/h2>\s*<div class="grid">[\s\S]*?<\/div>/;

const MAX_PER_BUCKET = 4;

// ---------------------------------------------------------------------------
// Stopwords / boilerplate filtering
// ---------------------------------------------------------------------------

const ENGLISH_STOPWORDS = new Set(
  ('a an the and or but of to in on at for with is are was were be been being ' +
    'this that these those it its as by from your you what when where which ' +
    'who will can do does did our we i my me us not no yes if than then so ' +
    'up down out over under again further once here there all any both each ' +
    'few more most other some such only own same too very just about into ' +
    'after before between during while').split(' ')
);

// Words that recur across nearly every page in this corpus because they're
// part of the shared templates, not because the pages are actually about
// the same thing. Excluding them is what keeps the similarity score
// meaningful instead of "everything is 80% similar to everything else".
const BOILERPLATE_STOPWORDS = new Set(
  ('best time visit month by the truth weather travel guide guides crowd ' +
    'crowds calendar budget itinerary itineraries 2026 honest real actually ' +
    'cost costs complete answer worth strategy hack hacks tips ultimate top ' +
    'things thing changes everything most underrated locals local pack packing ' +
    'plan planner planning free app roamwise blog data table faq gems hidden ' +
    'eat food day days night nights week weeks trip trips').split(' ')
);

const STOPWORDS = new Set([...ENGLISH_STOPWORDS, ...BOILERPLATE_STOPWORDS]);

// Used only to strip filler/number/month/region tokens out of a filename
// slug when deriving a destination display name (step 4 of cityName
// extraction, see extractCityName()). Deliberately generic rather than an
// exhaustive gazetteer — see README note in the PR about known misses.
const SLUG_FILLER = new Set(
  ('in of self drive from under solo backpacker week weeks day days ' +
    'itinerary itineraries budget guide complete india usa uae uk').split(' ')
);
const MONTHS = new Set(
  ('january february march april may june july august september october ' +
    'november december').split(' ')
);
// Common multi-token country/state suffixes this corpus uses in filenames
// (e.g. "south-africa", "sri-lanka", "new-zealand", "tamil-nadu"). Splitting
// on these lets the slug fallback isolate the city portion generically
// instead of a per-country lookup table.
const REGION_WORDS = new Set(
  ('india thailand japan china uae uk usa vietnam nepal indonesia colombia ' +
    'peru turkey egypt kenya mexico brazil argentina chile spain italy france ' +
    'germany austria greece portugal ireland netherlands denmark norway sweden ' +
    'finland iceland switzerland poland hungary croatia czech republic georgia ' +
    'jordan qatar oman morocco tanzania zanzibar fiji cuba philippines malaysia ' +
    'singapore cambodia sri lanka south africa new zealand hong kong himachal ' +
    'kerala karnataka sikkim tamil nadu arunachal uttarakhand rajasthan ' +
    'kazakhstan azerbaijan uzbekistan bhutan maldives seychelles mauritius ' +
    'panama korea').split(' ')
);

function tokenize(text) {
  return (text.toLowerCase().match(/[a-z][a-z'-]{2,}/g) || []).filter(
    (w) => !STOPWORDS.has(w)
  );
}

// ---------------------------------------------------------------------------
// HTML field extraction (regex-based; these are static, well-formed pages
// generated from a small set of known templates, not arbitrary HTML)
// ---------------------------------------------------------------------------

function extract(re, html) {
  const m = html.match(re);
  return m ? m[1].trim() : '';
}

function stripTags(html) {
  return html.replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim();
}

function getTitle(html) {
  return extract(/<title[^>]*>([^<]*)<\/title>/i, html);
}
function getDescription(html) {
  return extract(/<meta\s+name="description"\s+content="([^"]*)"/i, html);
}
function getH1(html) {
  const m = html.match(/<h1[^>]*>([\s\S]*?)<\/h1>/i);
  return m ? stripTags(m[1]) : '';
}
function getTags(html) {
  const out = [];
  const re = /<span class="tag">([^<]*)<\/span>/g;
  let m;
  while ((m = re.exec(html))) out.push(m[1].trim().toLowerCase());
  return out;
}
function getBodyText(html) {
  // Body content starts after the last </style> (or head close) in these
  // templates; falling back to the whole document is harmless (just means
  // a little inline CSS gets tokenized/scanned, which STOPWORDS mostly
  // absorbs anyway).
  // Strip out a previous run's own injected block (and the legacy
  // hand-authored predecessor it replaces) first — otherwise the anchor
  // text/labels this tool itself wrote in a prior run would feed back into
  // the next run's scoring and the output would drift instead of
  // converging, breaking idempotency.
  const cleaned = html.replace(MARKER_RE, '').replace(LEGACY_KEEP_EXPLORING_RE, '');
  const idx = cleaned.lastIndexOf('</style>');
  const slice = idx >= 0 ? cleaned.slice(idx + 8) : cleaned;
  return stripTags(slice);
}

const GENERIC_LEAD_WORDS = new Set(['what', 'when', 'how', 'why', 'the', 'is', 'are', 'best', 'top', 'a']);

function extractCityName(slug, title, h1) {
  const source = h1 || title;
  let m = source.match(/Best Time to Visit ([^:,(]+)/i);
  if (m) return m[1].trim();

  m = source.match(
    /^([A-Z][A-Za-zÀ-ɏ' -]+?) in (January|February|March|April|May|June|July|August|September|October|November|December)\b/
  );
  if (m) return m[1].trim();

  m = source.match(/^([A-Z][A-Za-zÀ-ɏ' -]{1,40}?):/);
  if (m && !GENERIC_LEAD_WORDS.has(m[1].trim().split(/\s+/)[0].toLowerCase())) {
    return m[1].trim();
  }

  // Fallback: derive from the filename slug by stripping filler/number/
  // month/region words, e.g. "cape-town-south-africa" -> "Cape Town".
  const words = slug.split('-').filter((w) => {
    if (/^\d+$/.test(w)) return false;
    if (SLUG_FILLER.has(w) || MONTHS.has(w) || REGION_WORDS.has(w) || STOPWORDS.has(w)) return false;
    return true;
  });
  if (words.length === 0) return null;
  return words.map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join(' ');
}

// Words too generic to trust alone as a "this page mentions that
// destination" signal (they're real words in a destination's derived name
// but also common vocabulary or a country name shared by ~100 other pages).
const TOO_GENERIC_FOR_MENTION = new Set(['india', 'world', 'best', 'city', 'asia', 'africa', 'europe']);

// ---------------------------------------------------------------------------
// Page loading
// ---------------------------------------------------------------------------

function listContentFiles(dir) {
  const full = path.join(ROOT, dir);
  if (!fs.existsSync(full)) return [];
  return fs
    .readdirSync(full)
    .filter((f) => f.endsWith('.html') && !SKIP_FILES.has(f.toLowerCase()))
    .sort()
    .map((f) => path.join(full, f));
}

function loadPage(file, section) {
  const html = fs.readFileSync(file, 'utf8');
  const slug = path.basename(file, '.html');
  const title = getTitle(html);
  const description = getDescription(html);
  const h1 = getH1(html);
  const tags = getTags(html);
  const bodyText = getBodyText(html);
  const cityName = extractCityName(slug, title, h1);

  const sigText = [title, description, h1, tags.join(' '), slug.replace(/-/g, ' ')].join(' ');
  const tokens = new Set(tokenize(sigText));

  // A short, clean label for the link's visible anchor text: prefer the
  // extracted destination name (reads better than a full SEO title), fall
  // back to the H1, then the raw <title>. Truncated because a handful of
  // pages (multi-destination roundups) have no clean short name and their
  // H1 runs 60+ characters — too long for a related-link card.
  const rawLinkText = cityName || h1 || title || slug;
  const linkText =
    rawLinkText.length > 46 ? rawLinkText.slice(0, 45).replace(/\s+\S*$/, '') + '…' : rawLinkText;

  return {
    file,
    section,
    slug,
    url: `${SITE}${section.urlPrefix}${slug}.html`,
    title,
    description,
    h1,
    tags,
    tagSet: new Set(tags),
    tokens,
    bodyTextLower: bodyText.toLowerCase(),
    cityName,
    linkText,
    html,
  };
}

function loadAllPages() {
  const pages = [];
  for (const section of SECTIONS) {
    for (const file of listContentFiles(section.dir)) {
      pages.push(loadPage(file, section));
    }
  }
  return pages;
}

// ---------------------------------------------------------------------------
// Similarity scoring
// ---------------------------------------------------------------------------

function jaccard(setA, setB) {
  if (setA.size === 0 || setB.size === 0) return 0;
  let intersection = 0;
  for (const v of setA) if (setB.has(v)) intersection++;
  const union = setA.size + setB.size - intersection;
  return union === 0 ? 0 : intersection / union;
}

function mentionsDestination(bodyTextLower, cityName) {
  if (!cityName) return false;
  const lower = cityName.toLowerCase();
  const words = lower.split(/\s+/);
  if (words.length === 1 && TOO_GENERIC_FOR_MENTION.has(words[0])) return false;
  const escaped = lower.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const re = new RegExp(`\\b${escaped}\\b`);
  return re.test(bodyTextLower);
}

function scorePair(a, b) {
  if (a === b) return 0;
  let score = 0;
  score += jaccard(a.tagSet, b.tagSet) * 2; // tags are the highest-precision signal
  score += jaccard(a.tokens, b.tokens);
  if (mentionsDestination(a.bodyTextLower, b.cityName)) score += 1.5;
  if (mentionsDestination(b.bodyTextLower, a.cityName)) score += 1.5;
  return score;
}

function relatedFor(page, candidates, bucketKey) {
  const scored = candidates
    .filter((c) => c.section.bucket === bucketKey && c.slug !== page.slug)
    .map((c) => ({ page: c, score: scorePair(page, c) }))
    .filter((s) => s.score > 0)
    .sort((x, y) => y.score - x.score || x.page.slug.localeCompare(y.page.slug));
  return scored.slice(0, MAX_PER_BUCKET).map((s) => s.page);
}

// ---------------------------------------------------------------------------
// HTML rendering
// ---------------------------------------------------------------------------

function escapeHtml(s) {
  return String(s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function renderCard(page) {
  return (
    `<a href="${page.url}" style="display:block;text-decoration:none;color:inherit;` +
    `border:1px solid #1E1E28;border-radius:14px;padding:14px 15px;background:#0E1018">` +
    `<b style="display:block;color:#fff;font-size:14.5px;margin-bottom:3px">${escapeHtml(page.linkText)}</b>` +
    `<span style="font-size:12px;color:#8A8880">${escapeHtml(page.section.bucket === 'guides' ? 'Guide' : page.section.bucket === 'blog' ? 'Article' : 'Itinerary')}</span>` +
    `</a>`
  );
}

function renderBlock(buckets) {
  const sections = SECTIONS.filter((s) => buckets[s.bucket] && buckets[s.bucket].length > 0)
    .map((s) => {
      const cards = buckets[s.bucket].map(renderCard).join('');
      return (
        `<h2 style="font-size:19px;margin:30px 0 10px;color:#E8BA6C">${escapeHtml(s.label)}</h2>` +
        `<div style="display:grid;grid-template-columns:repeat(auto-fill,minmax(200px,1fr));gap:10px;margin:0 0 8px">${cards}</div>`
      );
    })
    .join('');
  if (!sections) return '';
  return `${MARKER_START}\n<div>${sections}</div>\n${MARKER_END}`;
}

function injectBlock(html, block) {
  if (!block) {
    // Nothing to link to (e.g. a one-of-a-kind page) — remove any stale
    // block from a previous run rather than leaving an empty one behind.
    if (MARKER_RE.test(html)) return html.replace(MARKER_RE, '').replace(/\n{3,}/g, '\n\n');
    return html;
  }
  if (MARKER_RE.test(html)) {
    return html.replace(MARKER_RE, block);
  }
  if (LEGACY_KEEP_EXPLORING_RE.test(html)) {
    return html.replace(LEGACY_KEEP_EXPLORING_RE, block);
  }
  const footerIdx = html.search(/<footer[\s>]/i);
  if (footerIdx === -1) return null; // no known insertion point; leave untouched
  return html.slice(0, footerIdx) + block + '\n' + html.slice(footerIdx);
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

function main() {
  const checkOnly = process.argv.includes('--check');
  const pages = loadAllPages();

  let changed = 0;
  let skipped = 0;

  for (const page of pages) {
    const buckets = {};
    for (const section of SECTIONS) {
      buckets[section.bucket] = relatedFor(page, pages, section.bucket);
    }
    const block = renderBlock(buckets);
    const nextHtml = injectBlock(page.html, block);

    if (nextHtml === null) {
      skipped++;
      console.warn(`related-links: skipped (no <footer> to anchor on): ${path.relative(ROOT, page.file)}`);
      continue;
    }
    if (nextHtml !== page.html) {
      changed++;
      if (checkOnly) {
        console.log(`related-links --check: would update ${path.relative(ROOT, page.file)}`);
      } else {
        fs.writeFileSync(page.file, nextHtml, 'utf8');
      }
    }
  }

  console.log(
    `related-links: scanned ${pages.length} page(s), ${changed} ${checkOnly ? 'would change' : 'updated'}, ${skipped} skipped.`
  );

  if (checkOnly && changed > 0) process.exit(1);
}

if (require.main === module) {
  main();
}

module.exports = { loadAllPages, extractCityName, scorePair, relatedFor, tokenize, jaccard };
