/* Generate the classic-script offline seed from the one reviewed JSON catalogue. */
const fs=require('node:fs'),path=require('node:path');
const root=path.join(__dirname,'..'),schema=require('../design/catalogue-core.js');
const raw=fs.readFileSync(path.join(root,'design/catalogue.json'),'utf8'),data=JSON.parse(raw);
if(!schema.validate(data))throw new Error('Invalid design catalogue');
const output='/* Generated by tools/design-catalogue.cjs; edit catalogue.json. */\nwindow.RWDesignSeed = '+JSON.stringify(data)+';\n';
const target=path.join(root,'design/catalogue-seed.js');
if(process.argv.includes('--check')){
  if(fs.readFileSync(target,'utf8')!==output)throw new Error('Design seed drift; run node tools/design-catalogue.cjs');
  console.log('Design catalogue and offline seed agree: '+data.version);
}else fs.writeFileSync(target,output);
