#!/usr/bin/env node
/* Writes a crawlable static page for every artist whose `page` in creators/artists-data.json is /creators/<id>/.
   The browser page /creators/artist.html?a=<id> renders the same markup client-side and redirects here, so Google
   gets real HTML (title, bio, paintings, structured data) instead of an empty shell filled by JavaScript.
   A page is marked noindex until it has a written bio and at least one available painting with a photo, so thin
   pages never reach the index (see tools/generate-sitemap.js, which uses the same rule).
   usage: node tools/build-artist-pages.js [--check]      (npm run artists:build / artists:check) */
'use strict';
const fs = require('fs'), path = require('path');
const R = require('../creators/artist-render.js');
const ROOT = path.resolve(__dirname, '..'), SITE = 'https://www.roamwise.co.in', MARK = '<!-- generated by tools/build-artist-pages.js; edit creators/artists-data.json, not this file -->';
const DEFAULT_IMG = '/assets/img/roamwise-share-20261018.jpg';

function load() { return JSON.parse(fs.readFileSync(path.join(ROOT, 'creators/artists-data.json'), 'utf8')); }
function staticArtists(d) { return d.artists.filter((a) => a.page === '/creators/' + a.id + '/' && /^[a-z0-9-]+$/.test(a.id)); }
function shareImage(d, a) {
  const w = R.works(d, a).shown.find((x) => R.img(x.image));
  const src = (w && w.image) || (a.photo && R.img(a.photo.src)) || DEFAULT_IMG;
  return src.indexOf('https://') === 0 ? src : SITE + src;
}
function jsonLd(d, a, url) {
  const p = { '@context': 'https://schema.org', '@type': 'Person', name: a.name, jobTitle: 'Artist', url, worksFor: { '@type': 'Organization', name: a.studio } };
  if (a.bio) p.description = a.bio;
  if (a.state) p.address = { '@type': 'PostalAddress', addressRegion: a.state, addressCountry: 'IN' };
  const same = [a.instagram, a.website].filter((u) => typeof u === 'string' && u.indexOf('https://') === 0);
  if (same.length) p.sameAs = same;
  const works = R.works(d, a).shown.filter((w) => R.img(w.image)).map((w) => {
    const o = { '@type': 'VisualArtwork', name: w.title, creator: { '@type': 'Person', name: a.name }, image: w.image.indexOf('https://') === 0 ? w.image : SITE + w.image };
    if (w.medium) o.artMedium = w.medium;
    return o;
  });
  if (works.length) p.workExample = works;
  return JSON.stringify(p).replace(/</g, '\\u003c');
}
function page(d, a) {
  const e = R.esc, url = SITE + a.page, t = R.title(a), desc = R.description(a), idx = R.indexable(d, a);
  return `<!doctype html>
${MARK}
<html lang="en">
<head>
  <meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
  <title>${e(t)}</title>
  <meta name="description" content="${e(desc)}">
  <meta name="theme-color" content="#0b1020"><meta name="robots" content="${idx ? 'index,follow' : 'noindex,follow'}">
  <link rel="canonical" href="${e(url)}">
  <meta property="og:title" content="${e(t)}"><meta property="og:description" content="${e(desc)}">
  <meta property="og:image" content="${e(shareImage(d, a))}"><meta property="og:url" content="${e(url)}"><meta property="og:type" content="profile">
  <meta name="twitter:card" content="summary_large_image">
  <link rel="icon" href="/icons/favicon-32.png?v=20261018"><link rel="stylesheet" href="/creators/artists.css"><link rel="stylesheet" href="/creators/sacred-art.css"><link rel="stylesheet" href="/creators/artists-hub.css">
  <script type="application/ld+json">${jsonLd(d, a, url)}</script>
</head>
<body>
  <nav class="art-nav"><a href="/" class="art-brand"><img src="/icons/icon-192.png" width="32" height="32" alt="">RoamWise</a><div><a href="/creators/gallery.html">All artists</a><a href="/creators/sacred-art.html">Sacred art</a><a href="/creators/join-artist.html">Join free</a></div></nav>
  <main class="art-main" id="artistRoot">${R.html(d, a)}</main>
  <footer class="art-footer">RoamWise · Almora to Global · <a href="mailto:support@roamwise.co.in">Support</a> · <a href="/privacy.html">Privacy</a> · <a href="/creators/join-artist.html">Artist? Join free</a> · <a href="/creators/artist-terms.html">Artist terms</a></footer>
  <script src="/design/celebrate.js" defer></script>
</body></html>
`;
}
/* Directories this script owns: any creators/<dir>/index.html carrying the marker. */
function owned() {
  const base = path.join(ROOT, 'creators');
  return fs.readdirSync(base, { withFileTypes: true }).filter((x) => x.isDirectory()).map((x) => x.name)
    .filter((n) => { const f = path.join(base, n, 'index.html'); return fs.existsSync(f) && fs.readFileSync(f, 'utf8').includes(MARK); });
}
function build(check) {
  const d = load(), want = new Map(staticArtists(d).map((a) => [a.id, page(d, a)])), bad = [];
  for (const [id, html] of want) {
    const f = path.join(ROOT, 'creators', id, 'index.html');
    if (check) { if (!fs.existsSync(f) || fs.readFileSync(f, 'utf8') !== html) bad.push('creators/' + id + '/index.html is out of date'); continue; }
    fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, html);
  }
  for (const id of owned()) {
    if (want.has(id)) continue;
    if (check) bad.push('creators/' + id + '/ has no matching artist'); else fs.rmSync(path.join(ROOT, 'creators', id), { recursive: true });
  }
  if (check) {
    if (bad.length) { console.error('build-artist-pages --check:\n - ' + bad.join('\n - ') + '\nRun `npm run artists:build`.'); process.exit(1); }
    console.log('build-artist-pages --check: OK — ' + want.size + ' artist pages match artists-data.json.');
  } else console.log('build-artist-pages: wrote ' + want.size + ' artist pages (' + staticArtists(d).filter((a) => R.indexable(d, a)).length + ' indexable).');
}
if (require.main === module) build(process.argv.includes('--check'));
module.exports = { staticArtists, indexable: R.indexable, load };
